// Un émoji, avec son sélecteur de variante (U+FE0F) éventuel.
// Icônes illustrées (canaan-icon-art, 32 × 32) : appelées par un repère ⟦…⟧ dans les données et les textes.
const ART = typeof CANAAN_ICON_ART === 'object' ? CANAAN_ICON_ART : {};
const keys = Object.keys(MAP).sort((a, b) => b.length - a.length);
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const RX = new RegExp('⟦[a-z0-9_]+⟧|(?:' + keys.map(esc).join('|') + ')️?', 'gu');
const TEST = new RegExp(RX.source, 'u');
const nameOf = e =>
  e[0] === '⟦' ? (ART[e.slice(1, -1)] ? e.slice(1, -1) : null) : MAP[e.replace(/️/g, '')] || null;
const artOf = name =>
  ART[name] ? { inner: ART[name], box: 32 } : I[name] ? { inner: I[name], box: 24 } : null;
function svg(name, cls = 'ico') {
  const a = artOf(name);
  if (!a) return '';
  return (
    '<svg class="' +
    cls +
    (a.box === 32 ? ' art' : '') +
    '" viewBox="0 0 ' +
    a.box +
    ' ' +
    a.box +
    '" aria-hidden="true" focusable="false">' +
    a.inner +
    '</svg>'
  );
}
// Texte HTML : chaque émoji connu devient son icône (le reste est inchangé).
const html = text => String(text).replace(RX, e => svg(nameOf(e)) || (e[0] === '⟦' ? '' : e));
// Texte brut (info-bulles natives, champs) : l'émoji et l'espace qui le suit disparaissent.
const strip = text =>
  String(text)
    .replace(new RegExp('(?:' + RX.source + ')\\s?', 'gu'), '')
    .replace(/️/g, '');

// ---------------------------------------------------------------- Interface : remplacement à la volée
const SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'INPUT', 'TITLE', 'svg', 'SVG']);
const STRIP_ONLY = new Set(['OPTION']);
const ATTRS = ['title', 'aria-label', 'placeholder'];
// Chaque texte est d'abord traduit (client/i18n : rien en français), puis ses émojis deviennent des icônes.
function fixText(node) {
  const parent = node.parentNode;
  if (!parent || SKIP.has(parent.nodeName) || parent.closest?.('svg')) return;
  const raw = node.nodeValue;
  const text = translateText(raw);
  if (!text || !TEST.test(text)) {
    if (text !== raw) node.nodeValue = text;
    return;
  }
  if (STRIP_ONLY.has(parent.nodeName)) {
    node.nodeValue = strip(text);
    return;
  }
  const tpl = document.createElement('template'),
    // Émoji seul dans son élément (case d'objet, bouton du menu) : une icône un peu plus grande.
    solo = parent.childNodes.length === 1 && text.replace(RX, '').trim() === '';
  tpl.innerHTML = html(text.replace(/[&<>]/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' })[ch]));
  if (solo) tpl.content.querySelectorAll('svg.ico').forEach(el => el.classList.add('solo'));
  parent.replaceChild(tpl.content, node);
}
function fixAttrs(el) {
  for (const a of ATTRS) {
    const v = el.getAttribute?.(a);
    if (!v) continue;
    const text = translateText(v);
    if (TEST.test(text)) el.setAttribute(a, strip(text));
    else if (text !== v) el.setAttribute(a, text);
  }
}
function fixTree(root) {
  if (!root) return;
  if (root.nodeType === 3) return fixText(root);
  if (root.nodeType !== 1 && root.nodeType !== 11) return;
  if (root.nodeType === 1) {
    if (SKIP.has(root.nodeName)) return fixAttrs(root);
    fixAttrs(root);
  }
  const walker = document.createTreeWalker(root, 5);
  const texts = [];
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    if (n.nodeType === 3) texts.push(n);
    else fixAttrs(n);
  }
  texts.forEach(fixText);
}
function watch() {
  if (typeof MutationObserver === 'undefined' || !document.body || !document.createTreeWalker) return;
  fixTree(document.body);
  if (document.title) {
    const title = translateText(document.title);
    document.title = TEST.test(title) ? strip(title) : title;
  }
  new MutationObserver(list => {
    for (const m of list) {
      if (m.type === 'characterData') fixText(m.target);
      else if (m.type === 'attributes') fixAttrs(m.target);
      else for (const n of m.addedNodes) fixTree(n);
    }
  }).observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ATTRS
  });
}
if (typeof document !== 'undefined' && document.readyState === 'loading')
  document.addEventListener?.('DOMContentLoaded', watch);
else if (typeof document !== 'undefined') watch();

