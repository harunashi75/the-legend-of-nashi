// ---------------------------------------------------------------- Taille des textes
// Réglée dans les Paramètres (canaan-settings) : seules les polices grandissent. Dans l'interface, chaque taille
// en pixels est multipliée par --font-scale (CSS) ; sur le canevas du jeu (#game), la police des textes dessinés
// (noms, chiffres, bulles) l'est aussi. Les panneaux, les barres et la vue du monde gardent leur taille.
let textScale = 1.25;
export const canaanTextScale = () => textScale;
export const canaanSetTextScale = v => {
  textScale = Math.max(1, Math.min(2, Number(v) || 1));
  if (typeof document !== 'undefined' && document.documentElement?.style?.setProperty)
    document.documentElement.style.setProperty('--font-scale', String(textScale));
};
function patchFont() {
  if (typeof CanvasRenderingContext2D === 'undefined') return;
  const proto = CanvasRenderingContext2D.prototype,
    desc = Object.getOwnPropertyDescriptor(proto, 'font');
  if (!desc?.set) return;
  Object.defineProperty(proto, 'font', {
    configurable: true,
    enumerable: desc.enumerable,
    get() {
      return desc.get.call(this);
    },
    set(v) {
      if (textScale !== 1 && this.canvas?.id === 'game')
        v = String(v).replace(/(\d+(?:\.\d+)?)px/, (_, n) => Math.round(n * textScale * 10) / 10 + 'px');
      desc.set.call(this, v);
    }
  });
}
patchFont();
function patchCanvas() {
  if (typeof CanvasRenderingContext2D === 'undefined') return;
  const proto = CanvasRenderingContext2D.prototype,
    fill = proto.fillText,
    stroke = proto.strokeText,
    measure = proto.measureText;
  // Morceaux du texte : texte brut ou icône.
  const parts = s => {
    const out = [];
    let last = 0;
    for (const m of s.matchAll(RX)) {
      if (m.index > last) out.push({ text: s.slice(last, m.index) });
      const name = nameOf(m[0]);
      if (name) out.push({ icon: name });
      last = m.index + m[0].length;
    }
    if (last < s.length) out.push({ text: s.slice(last) });
    return out;
  };
  const sizeOf = ctx => {
    const m = /(\d+(?:\.\d+)?)px/.exec(ctx.font || '');
    return (m ? Number(m[1]) : 10) * 1.15;
  };
  function draw(ctx, s, x, y, filled) {
    const list = parts(s),
      size = sizeOf(ctx);
    for (const it of list) it.w = it.text !== undefined ? measure.call(ctx, it.text).width : size + 1;
    const total = list.reduce((a, it) => a + it.w, 0),
      align = ctx.textAlign,
      rtl = ctx.direction === 'rtl';
    let cx =
      align === 'center'
        ? x - total / 2
        : align === 'right' || (align === 'end' && !rtl) || (align === 'start' && rtl)
          ? x - total
          : x;
    const base = ctx.textBaseline,
      top =
        base === 'middle'
          ? y - size / 2
          : base === 'top' || base === 'hanging'
            ? y
            : base === 'bottom' || base === 'ideographic'
              ? y - size
              : y - size * 0.8;
    ctx.textAlign = 'left';
    for (const it of list) {
      if (it.text !== undefined) (filled ? fill : stroke).call(ctx, it.text, cx, y);
      else if (filled) {
        const img = image(it.icon);
        if (img && img.complete && img.naturalWidth) ctx.drawImage(img, cx, top, size, size);
      }
      cx += it.w;
    }
    ctx.textAlign = align;
  }
  // Textes du canevas : traduits (client/i18n), puis dessinés avec leurs icônes.
  proto.fillText = function (text, x, y, maxWidth) {
    const s = translateText(String(text));
    if (!TEST.test(s)) return fill.call(this, s, x, y, ...(maxWidth === undefined ? [] : [maxWidth]));
    draw(this, s, x, y, true);
  };
  proto.strokeText = function (text, x, y, maxWidth) {
    const s = translateText(String(text));
    if (!TEST.test(s)) return stroke.call(this, s, x, y, ...(maxWidth === undefined ? [] : [maxWidth]));
    draw(this, s, x, y, false);
  };
  proto.measureText = function (text) {
    const s = translateText(String(text));
    return measure.call(this, TEST.test(s) ? s.replace(RX, '　') : s);
  };
  // Images préparées d'avance : la première apparition d'une icône est déjà nette.
  for (const name of new Set([...Object.values(MAP), ...Object.keys(ART)])) image(name);
}
patchCanvas();

